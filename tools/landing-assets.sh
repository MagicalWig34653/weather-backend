#!/bin/sh
# Erzeugt Sources/RadarCore/LandingAssetData.swift (Base64 der Landingpage-Bilder) aus den Quellbildern des App-Repos.
# Aufruf: tools/landing-assets.sh <App-Repo-Pfad>   (benötigt cwebp, ffmpeg, base64)
# Quellen (App-Repo, design/appstore-screenshots): iphone/1206x2622/de (01, 02, 03, 04, 05), watch/422x514/de (01, 02),
# creative/universal-16x9.png (Open-Graph-Bild), tools/assets/AppIcon-1024.png.
# Die Radar- und Wolken-Screenshots werden unterhalb der Kopfzeile beschnitten (kein Widerspruch zwischen Banner und Archivregen).
set -eu
APP="${1:?App-Repo-Pfad fehlt}"
DS="$APP/design/appstore-screenshots"
SHOTS="$DS/iphone/1206x2622/de"
WATCH="$DS/watch/422x514/de"
OUT="$(dirname "$0")/../Sources/RadarCore/LandingAssetData.swift"
TMP="$(mktemp -d)"
W="cwebp -quiet -m 6 -sharp_yuv"
for w in 640 320; do
  s=""; [ "$w" = 320 ] && s="Small"
  $W -q 62 -crop 0 556 1206 2066 -resize $w 0 "$SHOTS/01-regenradar.png" -o "$TMP/radarLight$s.webp"
  $W -q 62 -crop 0 556 1206 2066 -resize $w 0 "$SHOTS/04-regenradar-dunkel.png" -o "$TMP/radarDark$s.webp"
  $W -q 62 -resize $w 0 "$SHOTS/02-orte.png" -o "$TMP/placesLight$s.webp"
  $W -q 62 -resize $w 0 "$SHOTS/05-orte-dunkel.png" -o "$TMP/placesDark$s.webp"
done
$W -q 55 -crop 0 556 1206 2066 -resize 640 0 "$SHOTS/03-wolken.png" -o "$TMP/clouds.webp"
$W -q 75 "$WATCH/01-ortsliste.png" -o "$TMP/watchList.webp"
$W -q 75 "$WATCH/02-ortsprognose.png" -o "$TMP/watchForecast.webp"
cwebp -quiet -q 80 -alpha_q 90 -resize 256 0 "$DS/tools/assets/AppIcon-1024.png" -o "$TMP/icon.webp"
# apple-touch-icon: opak (iOS rundet selbst), Palette für kleine Datei
ffmpeg -loglevel error -y -f lavfi -i color=c=0xc8c8c8:s=180x180:r=25:d=0.04 -i "$DS/tools/assets/AppIcon-1024.png" \
  -filter_complex "[1]scale=180:180[i];[0][i]overlay=format=auto,split[a][b];[a]palettegen=max_colors=96[p];[b][p]paletteuse=dither=none" -frames:v 1 "$TMP/appleIcon.png"
ffmpeg -loglevel error -y -i "$DS/creative/universal-16x9.png" -vf "crop=5244:2745:0:102,scale=1200:630" -q:v 9 -pix_fmt yuvj420p "$TMP/og.jpg"
{
  echo "// Generated by tools/landing-assets.sh. Do not edit. Images as Base64 (no file access at run time)."
  echo "enum LandingAssetData {"
  for n in icon appleIcon og radarLight radarDark radarLightSmall radarDarkSmall placesLight placesDark placesLightSmall placesDarkSmall clouds watchList watchForecast; do
    f="$TMP/$n.webp"; [ -f "$f" ] || f="$(ls "$TMP/$n".* )"
    printf '    static let %s = "%s"\n' "$n" "$(base64 < "$f" | tr -d '\n')"
  done
  echo "}"
} > "$OUT"
ls -l "$TMP" | awk '{print $5, $9}'
rm -rf "$TMP"

#!/bin/sh
# Erzeugt Sources/RadarCore/LandingAssetData.swift (Base64 der Landingpage-Bilder) aus den Quellbildern des App-Repos.
# Aufruf: tools/landing-assets.sh <App-Repo-Pfad>   (benötigt cwebp, base64)
# Quellen: design/appstore-screenshots/iphone/1206x2622/de (01, 02, 04, 05) und design/appstore-screenshots/tools/assets/AppIcon-1024.png
# Die Radar-Screenshots werden unterhalb der Kopfzeile beschnitten (kein Widerspruch zwischen Banner und Archivregen).
set -eu
APP="${1:?App-Repo-Pfad fehlt}"
SHOTS="$APP/design/appstore-screenshots/iphone/1206x2622/de"
OUT="$(dirname "$0")/../Sources/RadarCore/LandingAssetData.swift"
TMP="$(mktemp -d)"
cwebp -quiet -q 62 -m 6 -sharp_yuv -crop 0 556 1206 2066 -resize 640 0 "$SHOTS/01-regenradar.png" -o "$TMP/radarLight.webp"
cwebp -quiet -q 62 -m 6 -sharp_yuv -crop 0 556 1206 2066 -resize 640 0 "$SHOTS/04-regenradar-dunkel.png" -o "$TMP/radarDark.webp"
cwebp -quiet -q 62 -m 6 -sharp_yuv -resize 640 0 "$SHOTS/02-orte.png" -o "$TMP/placesLight.webp"
cwebp -quiet -q 62 -m 6 -sharp_yuv -resize 640 0 "$SHOTS/05-orte-dunkel.png" -o "$TMP/placesDark.webp"
cwebp -quiet -q 80 -alpha_q 90 -resize 256 0 "$APP/design/appstore-screenshots/tools/assets/AppIcon-1024.png" -o "$TMP/icon.webp"
{
  echo "// Generated by tools/landing-assets.sh. Do not edit. WebP images as Base64 (no file access at run time)."
  echo "enum LandingAssetData {"
  for n in icon radarLight radarDark placesLight placesDark; do
    printf '    static let %s = "%s"\n' "$n" "$(base64 < "$TMP/$n.webp" | tr -d '\n')"
  done
  echo "}"
} > "$OUT"
rm -rf "$TMP"
